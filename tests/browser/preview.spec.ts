import { test,expect } from '@playwright/test'
test('resident completes care, work, quest and home improvement and keeps progress on reload',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.route('https://**/*',async route=>{
    if(route.request().postData()?.includes('eth_gasPrice'))await route.fulfill({json:{jsonrpc:'2.0',id:1,result:'0x2540be400'}})
    else await route.abort()
  })
  await page.goto('/')
  await page.getByRole('button',{name:'Explore a local preview'}).click()
  await expect(page.locator('canvas')).toBeVisible()
  await page.getByRole('button',{name:'Call a friend'}).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('dialog').getByRole('button',{name:'Call a friend'}).click()
  await expect(page.getByRole('status')).toContainText('Call a friend complete',{timeout:20000})
  await expect.poll(async()=>Number(await page.getByRole('progressbar',{name:'Social'}).getAttribute('aria-valuenow'))).toBeGreaterThanOrEqual(90)
  await page.getByRole('button',{name:'Work a shift'}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Work a shift'}).click()
  await expect(page.getByRole('status')).toContainText('Job complete',{timeout:35000})
  await page.getByRole('button',{name:'+60',exact:true}).click()
  await page.getByRole('button',{name:'Improve home'}).click()
  await expect(page.getByRole('status')).toContainText('Home improved')
  await expect(page.locator('.game-header')).toContainText('Shared Dorm')
  await page.reload();await page.getByRole('button',{name:'Explore a local preview'}).click()
  await expect(page.locator('.game-header')).toContainText('Shared Dorm')
  await expect(page.getByRole('button',{name:'✓ Claimed',exact:true})).toHaveCount(1)
  await page.screenshot({path:'/tmp/chainworld-preview.png',fullPage:true})
  expect(errors).toEqual([])
})
